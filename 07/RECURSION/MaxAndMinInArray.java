public class MaxAndMinInArray {
    public static void main(String[] args) {
        int[] arr = {1, 4, 3, -5, -4, 8, 6};
        System.out.println(getMinEle(arr));
    }

    private static int getMinEle(int[] arr) {
        if(arr.length < 1){
            return arr[0];
        }
        
    }
}
